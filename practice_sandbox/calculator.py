def add(a, b):
    """
    Return the sum of a and b.
    
    Supports integers and floats. No type conversion or validation is performed;
    relies on Python's native addition semantics.
    
    Args:
        a: First operand (int or float).
        b: Second operand (int or float).
    
    Returns:
        The result of a + b (type depends on inputs).
    """
    return a + b
